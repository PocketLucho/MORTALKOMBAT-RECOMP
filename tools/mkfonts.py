#!/usr/bin/env python3
# mkfonts.py - embeds the menu fonts (SIL Open Font License, see src/third_party/fonts/OFL-*.txt)
# into src/app/fonts_embed.h
import os
d = os.path.join(os.path.dirname(__file__), '..', 'src', 'third_party', 'fonts')
out = ['// generated by tools/mkfonts.py - fonts under the SIL Open Font License 1.1 (src/third_party/fonts)', '#pragma once']
for var, f in [('font_title', 'Nosifer-Regular.ttf'), ('font_head', 'MetalMania-Regular.ttf'), ('font_body', 'Oswald.ttf')]:
    b = open(os.path.join(d, f), 'rb').read()
    out.append('static const unsigned char %s[%d] = {' % (var, len(b)))
    for i in range(0, len(b), 24):
        out.append(','.join(str(x) for x in b[i:i + 24]) + ',')
    out.append('};')
open(os.path.join(d, '..', '..', 'app', 'fonts_embed.h'), 'w').write('\n'.join(out) + '\n')
